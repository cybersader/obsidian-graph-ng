import fs from 'node:fs';
import { gzipSync, brotliCompressSync } from 'node:zlib';
import { createHash } from 'node:crypto';
import { root, git } from './gate-lib.mjs';
import path from 'node:path';
const bytes = fs.readFileSync(path.join(root, 'main.js'));
const report = { commit: git(['rev-parse', 'HEAD']).trim(), bytes: bytes.length, gzipBytes: gzipSync(bytes, { level: 9 }).length, brotliBytes: brotliCompressSync(bytes).length, sha256: createHash('sha256').update(bytes).digest('hex'), limits: { slice3Bytes: 250000, slice3GzipBytes: 70000, zeroDependencyTargetBytes: 150000, zeroDependencyTargetGzipBytes: 45000 }, policy: 'Enforce slice-3 minified ceilings; record tighter zero-dependency targets for the layout replacement. Run build first.' };
fs.mkdirSync(path.join(root, '.workspace/evidence'), { recursive: true });
fs.writeFileSync(path.join(root, '.workspace/evidence/bundle-size.json'), JSON.stringify(report, null, 2) + '\n');
console.log(JSON.stringify(report, null, 2));
if (report.bytes > report.limits.slice3Bytes || report.gzipBytes > report.limits.slice3GzipBytes) throw new Error('BUNDLE_SIZE_LIMIT: slice-3 ceiling exceeded');
