import { readFile, writeFile } from 'node:fs/promises';
import { FUNCTIONS } from '../src/core/expr/syntax';
const start = '<!-- expression-functions:start -->', end = '<!-- expression-functions:end -->';
const file = 'docs/declaration-format.md';
let text = await readFile(file, 'utf8');
const table = '| Callable | Receiver / scope | Arguments | Result |\n| --- | --- | --- | --- |\n' + Object.entries(FUNCTIONS).map(([name, [min, max, result, scope]]) => `| \`${name}\` | ${scope} | ${min === max ? min : `${min}–${max}`} | ${result} |`).join('\n');
const section = `${start}\n${table}\n${end}`;
if (text.includes(start)) text = text.slice(0, text.indexOf(start)) + section + text.slice(text.indexOf(end) + end.length);
else text += `\n## Callable inventory\n\nGenerated by \`./scripts/run.sh docs:expressions\` from the shared callable descriptor table; hand-written semantics and literal restrictions above remain authoritative.\n\n${section}\n`;
await writeFile(file, text);
